import Foundation

let suite = "trashketball.tests.\(UUID().uuidString)"
let defaults = UserDefaults(suiteName: suite)!
defer { defaults.removePersistentDomain(forName: suite) }
let game = GameStore(defaults: defaults)
let start = Date(timeIntervalSince1970: 1000)
game.configure(target: 3, duration: 30)
game.record(made: true, now: start)
assert(game.round.score == 0, "Cannot score before a round")
game.start(now: start)
game.configure(target: 1)
assert(game.round.targetMeters == 3, "Cannot alter points during a round")
game.record(made: true, now: start.addingTimeInterval(1))
game.record(made: false, now: start.addingTimeInterval(2))
assert(game.round.score == 1 && game.round.baskets == 1 && game.round.shots.count == 2)
game.undo(now: start.addingTimeInterval(3))
game.undo(now: start.addingTimeInterval(4))
assert(game.round.score == 0 && game.best == 0)
game.record(made: true, now: start.addingTimeInterval(5))
game.record(made: true, now: start.addingTimeInterval(30))
assert(game.round.score == 1, "Cannot score at/after deadline")
game.tick(now: start.addingTimeInterval(30))
assert(game.round.finished && game.best == 1)
assert(GameStore(defaults: defaults).best == 1, "Best survives relaunch")
game.reset()
assert(game.round.score == 0 && game.round.targetMeters == 3 && game.round.startedAt == nil)
let decoded = try JSONDecoder().decode(RoundState.self, from: JSONEncoder().encode(game.round))
assert(decoded == game.round, "Peer round encoding round trip")
let command = MotionCommand(client_id: "test", sequence: 1, sent_at: 1000, action: "stop", targetMeters: 2, speed: 25)
let decodedCommand = try JSONDecoder().decode(MotionCommand.self, from: JSONEncoder().encode(command))
assert(decodedCommand == command)
print("Game scoring, expiry, undo, persistence and movement encoding checks passed")

let beamGame = GameStore(defaults: defaults)
let beamStart = Date(timeIntervalSince1970: 2000)
beamGame.configure(target: 2)
beamGame.start(now: beamStart)
let basket = BeamEvent(id: UUID(), roundID: beamGame.round.id, timestamp: 2001, points: 1)
let sensor = BeamStatus(available: true, pin: 24, blocked: true, message: "test", breakCount: 1, events: [basket])
beamGame.applyBeam(sensor)
beamGame.applyBeam(sensor)
assert(beamGame.round.score == 1 && beamGame.round.baskets == 1, "Repeated polling cannot double count")
beamGame.tick(now: beamStart.addingTimeInterval(30))
var delayed = sensor
delayed.events = [BeamEvent(id: UUID(), roundID: beamGame.round.id, timestamp: 2029.9, points: 1)]
beamGame.applyBeam(delayed)
assert(beamGame.round.score == 2, "Accept a pre-deadline basket delivered after expiry")
delayed.events = [BeamEvent(id: UUID(), roundID: beamGame.round.id, timestamp: 2030, points: 1)]
beamGame.applyBeam(delayed)
assert(beamGame.round.score == 2, "Reject a basket at the deadline")
beamGame.reset(); beamGame.start(now: Date(timeIntervalSince1970: 2040))
beamGame.applyBeam(sensor)
assert(beamGame.round.score == 0, "No old-round basket leakage")
beamGame.end(now: Date(timeIntervalSince1970: 2042))
delayed.events = [BeamEvent(id: UUID(), roundID: beamGame.round.id, timestamp: 2043, points: 1)]
beamGame.applyBeam(delayed)
assert(beamGame.round.score == 0, "No basket after early end")
print("Beam event deduplication, deadline, delayed delivery and round isolation passed")
