import Foundation

let encoder = JSONEncoder(), decoder = JSONDecoder()
for action in [GuidanceRequest.Action.preview, .start, .stop, .endPreview] {
    let request = GuidanceRequest(action:action,target:2,sentAt:100)
    let restored = try decoder.decode(GuidanceRequest.self,from:encoder.encode(request))
    assert(restored.id == request.id && restored.action == action && restored.target == 2)
    assert(restored.isValid(at:100.5))
    assert(restored.isValid(at:110) == (action == .stop), "Delayed Start must never cause surprise movement; Stop always accepted")
}
assert(!GuidanceRequest(action:.start,target:9,sentAt:100).isValid(at:100))
assert(!GuidanceRequest(action:.start,target:2,sentAt:Double.nan).isValid(at:100))
var hold = GuidanceSensorHold()
hold.pause(at:10)
assert(!hold.ready(depth:9.9,uwb:10.1), "Pre-pause depth cannot authorize recovery")
assert(!hold.ready(depth:10.1,uwb:9.9), "Pre-pause UWB cannot authorize recovery")
assert(!hold.ready(depth:10.1,uwb:10.1))
for _ in 0..<10 { assert(!hold.ready(depth:10.1,uwb:10.1), "Re-evaluating one frame is not recovery") }
assert(!hold.ready(depth:10.2,uwb:10.1), "Repeated UWB update cannot authorize recovery")
assert(!hold.ready(depth:10.2,uwb:10.2))
assert(hold.ready(depth:10.3,uwb:10.3))
hold.pause(at:11)
assert(!hold.ready(depth:11.1,uwb:11.1), "New gap clears stability")
assert(hold.expired(at:12), "Repeated gaps must not extend the two-second deadline")
hold.reset()
assert(hold.began == nil && !hold.expired(at:20))
assert(!hold.ready(depth:20,uwb:20), "Stop clears recovery state")
let decision = ApproachDecision(recoverableSensorWait:true,message:"Stop · waiting for LiDAR")
let state = GuidanceStatus(sequence:42,requestID:UUID(),previewing:true,active:true,paused:true,target:2,
    decision:decision,note:"Paused · waiting for stable readings",canPreview:true,canStart:false,floor:"Confirmed")
let restored = try decoder.decode(GuidanceStatus.self,from:encoder.encode(state))
assert(restored.sequence == 42 && restored.active && restored.decision == decision && restored.note == state.note)
assert(restored.requestID == state.requestID && restored.floor == "Confirmed")
print("Guidance protocol: request/ack/status round trips, delayed Start rejection, unconditional Stop and bounded stable sensor recovery passed")

let command = MotionCommand(client_id:"can",sequence:1,sent_at:100,action:"forward",targetMeters:2,speed:100)
var reply = PiReply(drive:DriveStatus(enabled:true,state:"manual",message:"Moving",summonReady:true,
    left:100,right:100,commandID:command.id),error:nil,beam:nil)
assert(GuidancePiConfirmation.movement(command,reply:reply,httpCode:200,failed:false,now:100.1))
assert(!GuidancePiConfirmation.movement(command,reply:reply,httpCode:200,failed:false,now:100.3), "Late reply cannot revive a watchdog-expired command")
assert(!GuidancePiConfirmation.movement(command,reply:reply,httpCode:500,failed:false,now:100.1))
reply.drive?.commandID = "another-command"
assert(!GuidancePiConfirmation.movement(command,reply:reply,httpCode:200,failed:false,now:100.1))
reply.drive = DriveStatus(enabled:true,state:"stopped",message:"Stopped",summonReady:true,left:0,right:0,commandID:nil)
assert(GuidancePiConfirmation.stopped(reply:reply,httpCode:200,failed:false))
reply.error = "rejected"
assert(!GuidancePiConfirmation.stopped(reply:reply,httpCode:200,failed:false), "Recovery needs an accepted Stop, not just a zero-looking reply")
reply.error = nil; reply.drive?.left = 100
assert(!GuidancePiConfirmation.stopped(reply:reply,httpCode:200,failed:false))
print("Pi confirmation: matching live command, latency, HTTP errors and confirmed zero-output Stop checks passed")

var routeHold = GuidanceSensorHold()
routeHold.pause(at:10,timeout:8)
assert(!routeHold.expired(at:17.9) && routeHold.expired(at:18))
routeHold.pause(at:15,timeout:8)
assert(routeHold.expired(at:18), "Waiting must not extend the route hold deadline")
routeHold.reset(); routeHold.pause(at:20,timeout:8); routeHold.pause(at:20.5,timeout:2)
assert(routeHold.expired(at:22), "A sensor failure shortens a route wait; never extends it")
let differential = MotionCommand(decision:ApproachDecision(leftPercent:100,rightPercent:85,action:"forward",speed:100),clientID:"can",target:2)
let differentialRoundTrip = try decoder.decode(MotionCommand.self,from:encoder.encode(differential))
assert(differentialRoundTrip.action == "drive" && differentialRoundTrip.leftPercent == 100 && differentialRoundTrip.rightPercent == 85)
print("Bounded route wait and production differential command encoding passed")

// Phone and Pi wall clocks can differ arbitrarily; only local monotonic RTT matters.
var clockSync = PiClockSync()
assert(clockSync.timestamp(at:10) == nil)
assert(clockSync.observe(serverTime:1_700_000_000,sent:10,received:10.04))
let piStamp = clockSync.timestamp(at:10.14)!
assert(abs(piStamp-1_700_000_000.12) < 0.00001)
assert(clockSync.timestamp(at:15.04) == nil, "Old synchronization must not authorize motion")
assert(!clockSync.observe(serverTime:1_700_000_001,sent:11,received:11.3), "Congested samples cannot reset synchronization")
assert(!clockSync.observe(serverTime:Double.nan,sent:11,received:11.01))
assert(!clockSync.observe(serverTime:1_700_000_001,sent:11,received:10))
let wallOffsetCommand = MotionCommand(client_id:"can",sequence:2,sent_at:piStamp,action:"forward",targetMeters:2,speed:100)
let matchingReply = PiReply(drive:DriveStatus(enabled:true,state:"manual",message:"OK",summonReady:true,left:90,right:100,commandID:wallOffsetCommand.id),error:nil,beam:nil)
assert(GuidancePiConfirmation.movement(wallOffsetCommand,reply:matchingReply,httpCode:200,failed:false,now:100,elapsed:0.05), "Acknowledgement age must not subtract server time from phone time")
assert(!GuidancePiConfirmation.movement(wallOffsetCommand,reply:matchingReply,httpCode:200,failed:false,now:100,elapsed:0.3))
assert(clockSync.observe(serverTime:1_800_000_000,sent:12,received:12.04), "Pi clock changes must replace the old clock domain")
assert(abs(clockSync.timestamp(at:12.14)!-1_800_000_000.12) < 0.00001)
clockSync.reset()
assert(clockSync.timestamp(at:13) == nil)
print("Pi clock: large offsets, monotonic RTT, stale/high-latency/invalid sample rejection, clock jumps and acknowledgement-domain separation passed")

let movingForward = MotionCommand(client_id:"can",sequence:1,sent_at:100,action:"drive",targetMeters:2,speed:100,leftPercent:100,rightPercent:90)
let turnLeft = MotionCommand(client_id:"can",sequence:2,sent_at:100,action:"left",targetMeters:2,speed:45)
let turnRight = MotionCommand(client_id:"can",sequence:3,sent_at:100,action:"right",targetMeters:2,speed:45)
assert(MotionDispatchPolicy.interrupts(current:movingForward,desired:turnLeft), "Guidance must dispatch Left immediately like manual arrows")
assert(MotionDispatchPolicy.interrupts(current:turnLeft,desired:turnRight))
var slowerLeft = turnLeft; slowerLeft.speed = 40
assert(!MotionDispatchPolicy.interrupts(current:turnLeft,desired:slowerLeft), "Speed-only changes must not repeatedly cancel acknowledgements")
var correctedForward = movingForward; correctedForward.rightPercent = 85
assert(!MotionDispatchPolicy.interrupts(current:movingForward,desired:correctedForward))
print("Shared manual/guided dispatch: immediate direction handoff and serialized speed/trim changes passed")

